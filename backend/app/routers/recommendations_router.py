"""Explainable AI Cooling Recommendation Engine endpoints."""

from typing import Optional

from fastapi import APIRouter, Depends, HTTPException, Query
from sqlalchemy import desc
from sqlalchemy.orm import Session

from app.database import get_db
from app.models import CoolingRecommendation, EnvironmentalIndicator, HeatRiskScore, Neighbourhood
from app.recommendation_engine import generate_recommendations_for_neighbourhood
from app.risk_engine import compute_heat_risk

router = APIRouter(prefix="/recommendations", tags=["AI Cooling Recommendations"])


@router.get("")
def list_recommendations(
    neighbourhood_id: Optional[int] = Query(default=None),
    priority: Optional[str] = Query(default=None),
    db: Session = Depends(get_db),
):
    query = db.query(CoolingRecommendation, Neighbourhood).join(
        Neighbourhood, CoolingRecommendation.neighbourhood_id == Neighbourhood.id
    )
    if neighbourhood_id:
        query = query.filter(CoolingRecommendation.neighbourhood_id == neighbourhood_id)
    if priority:
        query = query.filter(CoolingRecommendation.priority_level == priority)

    rows = query.order_by(CoolingRecommendation.id).all()
    items = [
        {
            "id": rec.id,
            "neighbourhood_id": nb.id,
            "neighbourhood_name": nb.name,
            "zone": nb.zone,
            "intervention_type": rec.intervention_type,
            "title": rec.title,
            "rationale": rec.rationale,
            "target_location": rec.target_location,
            "priority_level": rec.priority_level,
            "expected_beneficiaries": rec.expected_beneficiaries,
            "estimated_cost_range": rec.estimated_cost_range,
            "maintenance_considerations": rec.maintenance_considerations,
            "triggered_rules": rec.triggered_rules,
            "generated_by": rec.generated_by,
            "is_synthetic_estimate": rec.is_synthetic_estimate,
        }
        for rec, nb in rows
    ]
    return {
        "disclaimer": "Recommendations are generated by a deterministic rule engine with explainable natural-language rationales. Cost ranges & beneficiary counts are indicative estimates and interventions are NOT marked complete until verified in the Admin tracker.",
        "count": len(items),
        "recommendations": items,
    }


@router.post("/generate/{neighbourhood_id}")
def regenerate_for_neighbourhood(neighbourhood_id: int, db: Session = Depends(get_db)):
    nb = db.query(Neighbourhood).filter(Neighbourhood.id == neighbourhood_id).first()
    if not nb:
        raise HTTPException(status_code=404, detail="Neighbourhood not found.")

    ind = (
        db.query(EnvironmentalIndicator)
        .filter(EnvironmentalIndicator.neighbourhood_id == nb.id)
        .order_by(desc(EnvironmentalIndicator.observation_date))
        .first()
    )
    if not ind:
        raise HTTPException(status_code=404, detail="No environmental indicators found for neighbourhood.")

    ind_dict = {
        "land_surface_temp_c": ind.land_surface_temp_c,
        "air_temp_c": ind.air_temp_c,
        "ndvi_vegetation_pct": ind.ndvi_vegetation_pct,
        "built_up_intensity_pct": ind.built_up_intensity_pct,
        "albedo_index": ind.albedo_index,
        "elderly_pct": ind.elderly_pct,
        "low_income_housing_pct": ind.low_income_housing_pct,
        "outdoor_worker_pct": ind.outdoor_worker_pct,
        "healthcare_distance_km": ind.healthcare_distance_km,
        "cooling_facility_coverage_pct": ind.cooling_facility_coverage_pct,
    }
    risk_res = compute_heat_risk(ind_dict, data_nature=ind.data_nature)
    new_recs = generate_recommendations_for_neighbourhood(
        {"name": nb.name, "zone": nb.zone, "population_estimate": nb.population_estimate},
        ind_dict,
        risk_res,
    )

    # Refresh stored recommendations for this neighbourhood
    db.query(CoolingRecommendation).filter(CoolingRecommendation.neighbourhood_id == nb.id).delete()
    saved = []
    for rec in new_recs:
        row = CoolingRecommendation(
            neighbourhood_id=nb.id,
            intervention_type=rec["intervention_type"],
            title=rec["title"],
            rationale=rec["rationale"],
            target_location=rec["target_location"],
            priority_level=rec["priority_level"],
            expected_beneficiaries=rec["expected_beneficiaries"],
            estimated_cost_range=rec.get("estimated_cost_range"),
            maintenance_considerations=rec["maintenance_considerations"],
            triggered_rules=rec["triggered_rules"],
            is_synthetic_estimate=True,
        )
        db.add(row)
        db.flush()
        saved.append({
            "id": row.id,
            "neighbourhood_id": nb.id,
            "neighbourhood_name": nb.name,
            "zone": nb.zone,
            **rec,
            "generated_by": row.generated_by,
            "is_synthetic_estimate": True,
        })
    db.commit()

    return {
        "neighbourhood_id": nb.id,
        "neighbourhood_name": nb.name,
        "analysed_metrics": {
            "exposure_score": risk_res["exposure_score"],
            "vulnerability_score": risk_res["vulnerability_score"],
            "cooling_deficit_score": risk_res["cooling_deficit_score"],
            "overall_risk_score": risk_res["overall_risk_score"],
            "vegetation_pct": ind.ndvi_vegetation_pct,
            "built_up_intensity_pct": ind.built_up_intensity_pct,
            "cooling_facility_coverage_pct": ind.cooling_facility_coverage_pct,
        },
        "recommendations": saved,
    }
